def wrap_untrusted(text):
    """パートナー等の自由入力をプロンプトに混ぜる際の信頼境界マーカー。"""
    if not text or not str(text).strip():
        return ""
    return f"<<<非信頼データ>>>\n{text}\n<<<非信頼データ終わり>>>"

